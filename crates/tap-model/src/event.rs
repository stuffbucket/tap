//! The raw event model: what a pane recorded, exactly as `TapEvent` in
//! `src/model.ts` describes it, with integer microseconds and an explicit
//! per-pane sequence number.

use serde::{Deserialize, Serialize};

use crate::jsnum;

/// Largest `cols`/`rows` a resize may carry (the native renderer's limit).
pub const MAX_GRID: u16 = u16::MAX;
/// Largest absolute `scroll` delta, in lines.
pub const MAX_SCROLL_DELTA: i64 = 1_000_000;

/// One raw event in a pane.
///
/// A pane's events are totally ordered by `(at_us, seq)`. Times never
/// decrease; `seq` strictly increases, so events recorded at the same
/// microsecond keep the order they were recorded in. Importing a legacy
/// project numbers each pane's events `0, 1, 2, …` in array order.
#[derive(Debug, Clone, PartialEq)]
pub struct RawEvent {
    /// Source time in microseconds from the project epoch.
    pub at_us: u64,
    /// Per-pane sequence number; strictly increasing within a pane.
    pub seq: u64,
    /// What happened.
    pub kind: EventKind,
}

/// The event lanes of a pane. See `docs/architecture.md`, "Recording
/// semantics".
#[derive(Debug, Clone, PartialEq)]
pub enum EventKind {
    /// Bytes read from the PTY.
    Output(Output),
    /// Bytes written to the PTY.
    Input(Input),
    /// The source terminal changed size.
    Resize {
        /// New column count, at least 1.
        cols: u16,
        /// New row count, at least 1.
        rows: u16,
    },
    /// The viewport scrolled by `delta` lines.
    Scroll {
        /// Lines scrolled; bounded by [`MAX_SCROLL_DELTA`].
        delta: i64,
    },
    /// A named point in time.
    Marker {
        /// The marker's label.
        label: String,
    },
    /// The pane moved on the canvas.
    Layout(PaneLayout),
    /// The pane was shown or hidden.
    Visibility {
        /// Whether the pane is visible from this event on.
        visible: bool,
    },
}

impl EventKind {
    /// The event's `type` as the JSON form spells it.
    pub fn type_name(&self) -> &'static str {
        match self {
            Self::Output(_) => "output",
            Self::Input(_) => "input",
            Self::Resize { .. } => "resize",
            Self::Scroll { .. } => "scroll",
            Self::Marker { .. } => "marker",
            Self::Layout(_) => "layout",
            Self::Visibility { .. } => "visibility",
        }
    }
}

/// Bytes read from the PTY.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Output {
    /// The exact bytes; authoritative.
    pub data: Vec<u8>,
    /// How the JSON form spelled `data` (export only).
    pub data_encoding: TextEncoding,
    /// Self-contained replay bytes, present when external Kitty media was
    /// normalised (`playbackData`).
    pub playback: Option<Playback>,
}

/// Replay bytes that stand in for [`Output::data`] during playback.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Playback {
    /// The bytes to feed the terminal instead of `data`.
    pub data: Vec<u8>,
    /// How the JSON form spelled `playbackData` (export only).
    pub encoding: TextEncoding,
}

/// Bytes written to the PTY.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Input {
    /// The exact bytes, or empty when redacted.
    pub data: Vec<u8>,
    /// How the JSON form spelled `data` (export only).
    pub data_encoding: TextEncoding,
    /// Where the input came from, when recorded.
    pub origin: Option<InputOrigin>,
    /// Whether the bytes were withheld. `None` means the field was absent;
    /// `Some(false)` is kept so export reproduces an explicit `false`.
    pub redacted: Option<bool>,
}

/// The `origin` of an input event.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum InputOrigin {
    /// Typed at a keyboard.
    Keyboard,
    /// Pasted.
    Paste,
    /// Generated by the recording terminal in answer to a query.
    TerminalReply,
    /// Typed by a VHS tape.
    Vhs,
    /// Sent by other automation.
    Automation,
}

/// How the legacy JSON form spelled a byte string.
///
/// This is presentation, not data: the bytes are the same either way. It is
/// kept only so that exporting an imported project reproduces the original
/// JSON.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum TextEncoding {
    /// No `encoding` field (which means UTF-8).
    #[default]
    Unspecified,
    /// `"encoding": "utf8"`.
    Utf8,
    /// `"encoding": "base64"`.
    Base64,
}

/// A pane's rectangle in normalised canvas coordinates (`0..=1`).
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PaneLayout {
    /// Left edge.
    #[serde(serialize_with = "jsnum::serialize")]
    pub x: f64,
    /// Top edge.
    #[serde(serialize_with = "jsnum::serialize")]
    pub y: f64,
    /// Width.
    #[serde(serialize_with = "jsnum::serialize")]
    pub width: f64,
    /// Height.
    #[serde(serialize_with = "jsnum::serialize")]
    pub height: f64,
}

impl PaneLayout {
    /// Checks the rules `validLayout` in `src/model.ts` applies: finite,
    /// non-negative origin, positive size, inside the canvas (with the same
    /// 1e-6 tolerance).
    pub fn validate(&self, field: &str) -> Result<(), String> {
        for (name, value) in [
            ("x", self.x),
            ("y", self.y),
            ("width", self.width),
            ("height", self.height),
        ] {
            if !value.is_finite() {
                return Err(format!("{field}.{name} must be finite"));
            }
        }
        if self.x < 0.0 || self.y < 0.0 || self.width <= 0.0 || self.height <= 0.0 {
            return Err(format!(
                "{field} must have non-negative origin and positive size"
            ));
        }
        if self.x + self.width > 1.000_001 || self.y + self.height > 1.000_001 {
            return Err(format!("{field} must fit inside the normalized canvas"));
        }
        Ok(())
    }
}

impl RawEvent {
    /// Checks the per-event rules `validateProject` applies (everything except
    /// ordering and the project duration, which need context).
    pub fn validate(&self, field: &str) -> Result<(), String> {
        match &self.kind {
            EventKind::Resize { cols, rows } => {
                if *cols == 0 || *rows == 0 {
                    return Err(format!(
                        "{field}: resize cols and rows must be from 1 through {MAX_GRID}"
                    ));
                }
            }
            EventKind::Scroll { delta } => {
                if delta.unsigned_abs() > MAX_SCROLL_DELTA.unsigned_abs() {
                    return Err(format!(
                        "{field}: scroll delta must be within ±{MAX_SCROLL_DELTA}"
                    ));
                }
            }
            EventKind::Layout(layout) => layout.validate(&format!("{field}.layout"))?,
            EventKind::Output(_)
            | EventKind::Input(_)
            | EventKind::Marker { .. }
            | EventKind::Visibility { .. } => {}
        }
        Ok(())
    }
}
